import os
import pandas as pd
from PIL import Image

import torch
from torch.utils.data import Dataset
from torchvision import transforms


class MultiTaskFruitDataset(Dataset):
    def __init__(self, csv_file, images_root, is_train=True):
        """
        csv_file: path to train_v2.csv / val_v2.csv
        images_root: path to RipeNet 2.0 folder
        """
        self.data = pd.read_csv(csv_file)
        self.images_root = images_root
        self.is_train = is_train

        # Production-Grade Image Preprocessing & Augmentation
        if is_train:
            self.transform = transforms.Compose([
                transforms.RandomResizedCrop(224, scale=(0.8, 1.0)),
                transforms.RandomHorizontalFlip(),
                transforms.RandomRotation(15),
                transforms.ColorJitter(brightness=0.2, contrast=0.2, saturation=0.2),
                transforms.ToTensor(),
                transforms.Normalize(mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225])
            ])
        else:
            self.transform = transforms.Compose([
                transforms.Resize((224, 224)),
                transforms.ToTensor(),
                transforms.Normalize(mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225])
            ])

    def __len__(self):
        return len(self.data)

    def __getitem__(self, idx):
        row = self.data.iloc[idx]

        # Use the relative_path generated by our prepare script
        image_path = os.path.join(self.images_root, row["relative_path"])

        try:
            if not os.path.exists(image_path):
                raise FileNotFoundError(f"❌ Image not found: {image_path}")

            image = Image.open(image_path).convert("RGB")
            image = self.transform(image)
        except Exception as e:
            # 🚨 Recovery Logic: If this image is corrupt, try the NEXT one in the list
            # This prevents the whole training from crashing
            print(f"⚠️ Skipping corrupt image: {image_path} | Error: {e}")
            new_idx = (idx + 1) % len(self.data)
            return self.__getitem__(new_idx)

        # 🎯 Multi-Task Labels
        fruit_id = torch.tensor(row["fruit_id"], dtype=torch.long)         # Identity (0-5)
        ripeness_id = torch.tensor(row["ripeness_id"], dtype=torch.long)   # Ripeness (0-2)
        days_rem = torch.tensor([row["days_remaining"]], dtype=torch.float32) # Regression (-2 to 10)

        return image, {
            "fruit_id": fruit_id,
            "ripeness_id": ripeness_id,
            "days_remaining": days_rem
        }
